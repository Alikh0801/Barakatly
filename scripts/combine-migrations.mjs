// Joins every migration into one file, in order, for setting up a fresh
// Supabase project (the pre-production one) from the SQL Editor in one go.
//
//   npm run db:combine   ->   supabase/pre/all_migrations.sql
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "supabase", "migrations");
const out = path.join(root, "supabase", "pre", "all_migrations.sql");

const files = fs
  .readdirSync(dir)
  .filter((name) => /^\d+_.+\.sql$/.test(name))
  .sort();

const parts = files.map(
  (name) => `-- ===== ${name} =====\n${fs.readFileSync(path.join(dir, name), "utf8").trimEnd()}\n`,
);

const header = `-- Generated by scripts/combine-migrations.mjs from ${files[0]} … ${files.at(-1)}.
-- Do not edit: change supabase/migrations and run \`npm run db:combine\`.
-- For an empty Supabase project only; never run it against the live database.
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${header}\n${parts.join("\n")}`);
console.log(`${files.length} migrations -> ${path.relative(root, out)}`);
